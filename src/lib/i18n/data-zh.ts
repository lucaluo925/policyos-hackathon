type Pick = (en: string, key: string) => string;

export function zhData(locale: Locale) {
  const zh = locale === 'zh';
  const from = (map: Record<string, string>): Pick => (en) => (zh ? map[en] ?? en : en);
  return {
    region: from(REGION_ZH),
    income: from(INCOME_ZH),
    gov: from(GOV_ZH),
    status: from(STATUS_ZH),
    metricName: (slug: string, en: string) => (zh ? METRIC_ZH[slug]?.[0] ?? en : en),
    metricDesc: (slug: string, en: string) => (zh ? METRIC_ZH[slug]?.[1] ?? en : en),
    policyTitle: (id: string, en: string) => (zh ? POLICY_ZH[id]?.[0] ?? en : en),
    policyDesc: (id: string, en: string) => (zh ? POLICY_ZH[id]?.[1] ?? en : en),
  };
}
